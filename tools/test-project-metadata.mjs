import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const moduleURL=t=>'data:text/javascript;base64,'+Buffer.from(t).toString('base64');
const data=await readFile(new URL('../js/data.js',import.meta.url),'utf8');
const source=(await readFile(new URL('../js/projects-data.js',import.meta.url),'utf8')).replace(/from '\.\/data\.js\?[^']+'/g,"from '"+moduleURL(data)+"'");
const {PRO_CARDS,HOURLY_RATE}=await import(moduleURL(source));
const {PAGES}=await import(moduleURL(await readFile(new URL('../js/pages.js',import.meta.url),'utf8')));
assert.ok(!PRO_CARDS.some(p=>p.id==='charte'));
assert.equal(PAGES['projet-charte'],undefined);
const finance=PRO_CARDS.find(p=>p.id==='finance');
assert.equal(finance.time,'25 min / jour');assert.equal(finance.money,'≈ 9 800 € / an');
assert.match(finance.moneyCtx,/93,75/);assert.match(finance.moneyCtx,/225 jours/);
assert.equal((25/60*225*HOURLY_RATE).toFixed(2),'9819.38');
assert.match(PAGES['projet-financier'].html,/9 819,38/);
const moteur=PRO_CARDS.find(p=>p.id==='moteur44');
assert.ok(moteur&&moteur.pro&&PAGES[moteur.pro.id]);
assert.equal(moteur.diag.length,5);
assert.equal(moteur.money,'104 740–130 925 € / an');
assert.equal(moteur.time,'15 min / rapport');
assert.equal((Math.round(15*Math.round(HOURLY_RATE*100)/60)/100).toFixed(2),'26.19');
assert.ok(moteur.timeCtx.includes('bonne ligne Excel')&&moteur.timeCtx.includes('Q18'));
assert.equal(moteur.diag[3][2],'q18');
const ppMoso=PRO_CARDS.find(p=>p.id==='powerbi');
assert.equal(ppMoso.time,'100–167 h / an');
assert.equal(ppMoso.money,'10 474–17 456,67 € / an');
assert.equal(Math.round(15*Math.round(HOURLY_RATE*100)/60)/100,26.19);
assert.equal(Math.round(20*Math.round(HOURLY_RATE*100)/60)/100,34.91);
assert.equal(10*40/60,400/60);
assert.equal((10*40/60*HOURLY_RATE).toFixed(2),'698.27');
assert.equal((15*500/60*HOURLY_RATE).toFixed(2),'13092.50');
assert.equal((20*500/60*HOURLY_RATE).toFixed(2),'17456.67');
assert.match(ppMoso.extraGains[1].time,/6 h 40/);
assert.match(ppMoso.extraGains[0].money,/10 474/);
for(const id of ['projet-3','projet-4']){assert.match(PAGES[id].html,/400 à 500 plans de prévention/);assert.match(PAGES[id].html,/698,27/);assert.ok(!PAGES[id].html.includes('3 à 5 minutes'));}
assert.equal(ppMoso.diag[1][2],'vm');
assert.match(ppMoso.diag[2][1],/SharePoint/);
assert.match(ppMoso.diag[3][0],/Archivage/);
for(const id of ['projet-3','projet-4'])assert.ok(PAGES[id].html.includes('15 à 20 minutes économisées par plan de prévention'));
for(const project of PRO_CARDS){
 const file=await readFile(new URL('../assets/dioramas/'+project.id+'.glb',import.meta.url));
 assert.equal(file.toString('ascii',0,4),'glTF');
 const gltf=JSON.parse(file.toString('utf8',20,20+file.readUInt32LE(12)));
 for(let i=0;i<project.diag.length;i++)assert.ok(gltf.nodes.some(n=>n.name==='StepAnchor_'+i),project.id+' missing action '+i);
}
